/// Validates supported desktop capabilities and generates disposable
/// registration.
pub fn generate(
	root: &Path,
	config: &LeptoskitConfig,
	registry: &Registry,
	target: Target,
) -> Result<()> {
	anyhow::ensure!(
		matches!(target, Target::Linux | Target::Windows | Target::Tui),
		"the Rust desktop runner requires Linux, Windows, or a terminal"
	);
	anyhow::ensure!(
		!config.codepush.enabled,
		"the {} runner does not support code push yet; set codepush.enabled = false before \
		 building this platform",
		target.platform()
	);
	// Resolving the registry left out, with a warning, every plugin the
	// runner can't run; any left here that doesn't resolve is an error.
	let implementations = registry.implementations(target)?;
	let generated = generated_dir(root, target);

	for directory in [root.join(".leptoskit"), generated.clone()] {
		match std::fs::symlink_metadata(&directory) {
			Ok(metadata) => {
				anyhow::ensure!(
					metadata.is_dir() && !metadata.file_type().is_symlink(),
					"{} must be an ordinary generated directory",
					directory.display()
				);
			}

			Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
			Err(error) => return Err(error).context("inspect generated desktop directory"),
		}
	}

	let registrant = if matches!(target, Target::Linux) {
		let mut rust = String::from(
			"// Generated by leptoskit. Edit native.plugins and the runner's Cargo dependencies \
			 instead.\n\n// Runners made before plugins ran on Linux call this, and it does \
			 nothing.\npub fn configure<B: leptoskit::native::NativeBackend>(_host: &mut \
			 leptoskit::wasm::WasmHost<B>) {}\n\n/// Installs the plugins `native.plugins` \
			 selects into the guest.\npub fn plugins<B: leptoskit::native::NativeBackend>(\n    \
			 plugins: &mut leptoskit_bridge_ffi::app::PluginHost,\n    host: &mut \
			 leptoskit::wasm::WasmHost<B>,\n) -> Result<(), Box<dyn std::error::Error>> {\n",
		);

		let rust_plugins = implementations
			.iter()
			.filter_map(|(_, _, implementation)| implementation.rust());

		// Only factories that keep files or take the context need the app's
		// folders.
		if rust_plugins.clone().any(|registration| {
			matches!(
				(&registration.constructor, registration.flavour),
				(Constructor::ContextFactory(_), _)
					| (
						Constructor::Factory(_),
						Flavour::Sync | Flavour::Worker | Flavour::MainThread
					)
			)
		}) {
			let application = if config.native.package_id.is_empty() {
				&config.app.name
			} else {
				&config.native.package_id
			};

			writeln!(
				rust,
				"    let context = leptoskit_bridge_ffi::app::desktop_context({application:?})?;"
			)?;
		}

		if rust_plugins.clone().next().is_none() {
			rust.push_str("    let _ = (plugins, host);\n");
		}

		for (_, plugin, implementation) in &implementations {
			register_rust_plugin(plugin, implementation, &Installer::DESKTOP, &mut rust)?;
		}

		rust.push_str("    Ok(())\n}\n");
		rust
	} else {
		"// Generated by leptoskit. Native desktop capabilities are not enabled.\npub fn \
		 configure<B: leptoskit::native::NativeBackend>(\n_host: &mut \
		 leptoskit::wasm::WasmHost<B>,\n) {}\n"
			.to_owned()
	};

	write(&generated.join("registrant.rs"), &registrant)
}

/// Compiles the app-owned runner and packages its guest beside the executable.
/// `features` turns on what the selected plugins need, such as their
/// `async-host` features.
pub fn build(
	root: &Path,
	config: &LeptoskitConfig,
	target: Target,
	release: bool,
	features: &[String],
) -> Result<()> {
	let generated = generated_dir(root, target);
	let manifest = host_dir(root, target).join("Cargo.toml");
	anyhow::ensure!(manifest.is_file(), "missing {}", manifest.display());
	let mut command = Command::new("cargo");
	command
		.current_dir(root)
		.args(["build", "--manifest-path"])
		.arg(&manifest)
		.args(["--bins", "--target-dir"])
		.arg(generated.join("target"))
		.args([
			"--message-format=json-render-diagnostics",
			"--no-default-features",
		])
		.stdout(Stdio::piped())
		.stderr(Stdio::inherit());

	if !features.is_empty() {
		command.args(["--features", &features.join(",")]);
	}

	super::set_log_level(&mut command, config);

	if release {
		command.arg("--release");
	} else {
		command.args(super::DEBUG_HOST_ARGUMENTS);
	}

	let mut child = command
		.spawn()
		.context("start desktop runner compilation")?;
	let stdout = child.stdout.take().context("Cargo stdout unavailable")?;
	let executable = executable_in_messages(BufReader::new(stdout));
	let status = child
		.wait()
		.context("wait for desktop runner compilation")?;
	anyhow::ensure!(status.success(), "desktop runner compilation failed");
	let executable = executable?.context("Cargo produced no desktop executable")?;
	let bundle = assemble(root, config, target, &executable)?;
	println!("built application at {}", bundle.display());

	Ok(())
}

/// Where a build puts the runner's executable: `.leptoskit/<platform>/app/`,
/// named after the app.
pub(crate) fn application(root: &Path, config: &LeptoskitConfig, target: Target) -> PathBuf {
	let name = if matches!(target, Target::Windows) || (target.builds_on_host() && cfg!(windows)) {
		format!("{}.exe", config.app.name)
	} else {
		config.app.name.clone()
	};

	generated_dir(root, target).join("app").join(name)
}

/// Reads Cargo's artifact path rather than guessing its target/profile
/// layout. The compiler's diagnostics print along the way; with
/// `--message-format=json-render-diagnostics` they exist only in this
/// stream, so a reader that dropped them hid warnings and the errors that
/// explain a failed build.
fn executable_in_messages(messages: impl BufRead) -> Result<Option<PathBuf>> {
	let mut executable = None;
	let mut multiple = false;

	crate::cargo_messages::stream(messages, |message| {
		if message.reason == "compiler-artifact" && message.executable.is_some() {
			multiple |= executable.is_some();
			executable.clone_from(&message.executable);
		}
	})?;
	anyhow::ensure!(!multiple, "Cargo produced multiple desktop executables");

	Ok(executable)
}

fn assemble(
	root: &Path,
	config: &LeptoskitConfig,
	target: Target,
	executable: &Path,
) -> Result<PathBuf> {
	let generated = generated_dir(root, target);
	let bundle = generated.join("app");
	copy(executable, &application(root, config, target))?;
	copy(
		&generated.join("assets/app.wasm"),
		&bundle.join("assets/app.wasm"),
	)?;
	let icon_platform = match target {
		Target::Windows => Some(crate::icons::Platform::Windows),
		Target::Linux => Some(crate::icons::Platform::Linux),
		_ => None,
	};
	if let Some(platform) = icon_platform {
		crate::icons::write(root, config, platform, &bundle)?;
	}
	Ok(bundle)
}

#[cfg(test)]
mod tests {
	use leptoskit_config::MissingPlugins;

	use super::*;

	fn registry(root: &Path, package: &str) -> Registry {
		Registry {
			package: package.into(),
			plugins: Vec::new(),
			support: Vec::new(),
			bridge: root.join("bridge"),
			target: root.join("target"),
			host_features: vec![],
			devtools_feature: None,
			missing: Vec::new(),
			scene3d: false,
		}
	}

	fn plugin(metadata: serde_json::Value) -> super::super::registry::Plugin {
		serde_json::from_value(metadata).unwrap()
	}

	#[test]
	fn skips_plugins_the_runner_cannot_run_without_replacing_registration() {
		let root = std::env::temp_dir().canonicalize().unwrap().join(format!(
			"leptoskit-desktop-registration-{}",
			std::process::id()
		));
		write(&root.join("windows/Cargo.toml"), "# owned manifest").unwrap();
		let registry = registry(&root, "desktop_windows");
		let mut config = LeptoskitConfig::default();
		generate(&root, &config, &registry, Target::Windows).unwrap();
		let path = root.join(".leptoskit/windows/registrant.rs");
		let original = std::fs::read(&path).unwrap();
		config.codepush.enabled = true;

		let error = generate(&root, &config, &registry, Target::Windows).unwrap_err();
		assert!(error.to_string().contains("codepush.enabled = false"));
		config.codepush.enabled = false;
		let mut registry = registry;
		registry.plugins.push(plugin(
			serde_json::json!({"name": "filesystem", "rust-type": "Plugin"}),
		));
		// Unresolved plugins never reach the generator.
		let error = generate(&root, &config, &registry, Target::Windows).unwrap_err();
		assert!(error.to_string().contains("filesystem"));
		assert_eq!(std::fs::read(&path).unwrap(), original);

		// The Windows runner can't register plugins yet: they are left out
		// with a warning, and the registrant stays empty.
		let mut strict = Registry {
			plugins: Vec::new(),
			missing: Vec::new(),
			scene3d: false,
			..registry
		};
		strict.plugins.push(plugin(
			serde_json::json!({"name": "filesystem", "rust-type": "Plugin"}),
		));
		assert!(
			strict
				.select(Target::Windows, MissingPlugins::Error)
				.unwrap_err()
				.to_string()
				.contains("filesystem can't run on Windows")
		);
		let mut registry = strict;
		registry.plugins.push(plugin(
			serde_json::json!({"name": "filesystem", "rust-type": "Plugin"}),
		));
		registry
			.select(Target::Windows, MissingPlugins::Warn)
			.unwrap();
		assert_eq!(
			registry.warnings().collect::<Vec<_>>(),
			[
				"warning: filesystem can't run on Windows: the Windows runner doesn't run plugins \
				 yet; calls fail with Unavailable"
			]
		);
		generate(&root, &config, &registry, Target::Windows).unwrap();

		assert_eq!(std::fs::read(path).unwrap(), original);
		std::fs::remove_dir_all(root).unwrap();
	}

	#[test]
	fn the_linux_registrant_installs_each_plugin_in_its_app_directories() {
		let root = std::env::temp_dir().canonicalize().unwrap().join(format!(
			"leptoskit-linux-registration-{}",
			std::process::id()
		));
		write(&root.join("linux/Cargo.toml"), "# owned manifest").unwrap();
		let mut config = LeptoskitConfig::default();
		config.app.name = "field".into();
		config.native.package_id = "dev.example.field".into();
		let path = root.join(".leptoskit/linux/registrant.rs");

		let mut registry = registry(&root, "field_linux");
		generate(&root, &config, &registry, Target::Linux).unwrap();
		let empty = std::fs::read_to_string(&path).unwrap();
		assert!(empty.contains("pub fn configure<B: leptoskit::native::NativeBackend>"));
		assert!(empty.contains("let _ = (plugins, host);"));
		assert!(!empty.contains("desktop_context"));

		let os = || {
			let mut os = plugin(serde_json::json!({"name": "os", "rust-type": "Os"}));
			os.crate_name = "leptoskit_plugin_os".into();
			os
		};
		let mut store = plugin(serde_json::json!({
			"name": "store", "rust-factory": "from_app_dirs", "rust-worker": true
		}));
		store.crate_name = "leptoskit_plugin_store".into();
		let mut clipboard = plugin(serde_json::json!({
			"name": "clipboard",
			"linux": {"rust-factory": "from_context", "rust-context": true}
		}));
		clipboard.crate_name = "leptoskit_plugin_clipboard".into();
		let mut http = plugin(serde_json::json!({
			"name": "http", "rust-factory": "from_config", "rust-async": true
		}));
		http.crate_name = "leptoskit_plugin_http".into();
		http.options_json = Some(r#"{"origins":["https://api.example.com"]}"#.into());

		registry.plugins = vec![os()];
		registry
			.select(Target::Linux, MissingPlugins::Error)
			.unwrap();
		generate(&root, &config, &registry, Target::Linux).unwrap();
		let stateless = std::fs::read_to_string(&path).unwrap();
		assert!(!stateless.contains("desktop_context"), "{stateless}");
		assert!(!stateless.contains("let _ = (plugins, host);"));

		registry.plugins = vec![os(), store, clipboard, http];
		registry
			.select(Target::Linux, MissingPlugins::Error)
			.unwrap();
		generate(&root, &config, &registry, Target::Linux).unwrap();

		let registrant = std::fs::read_to_string(&path).unwrap();
		for line in [
			"    let context = leptoskit_bridge_ffi::app::desktop_context(\"dev.example.field\")?;",
			"    plugins.install(host, Box::new(leptoskit_plugin_os::Os::default()))?;",
			"    plugins.install_worker(host, \
			 Box::new(leptoskit_plugin_store::from_app_dirs(&context.data_dir, \
			 &context.cache_dir)?))?;",
			"    plugins.install(host, \
			 Box::new(leptoskit_plugin_clipboard::from_context(&context)?))?;",
			"    plugins.install_async(host, \
			 std::sync::Arc::new(leptoskit_plugin_http::from_config(\"{\\\"origins\\\":[\\\"https://api.example.com\\\"]}\")?))?;",
		] {
			assert!(registrant.contains(line), "{line}\nin\n{registrant}");
		}
		assert!(registrant.ends_with("    Ok(())\n}\n"));
		std::fs::remove_dir_all(root).unwrap();
	}

	#[test]
	fn follows_cargos_executable_and_rejects_ambiguous_artifacts() {
		let messages = concat!(
			"{\"reason\":\"compiler-message\",\"rendered\":\"warning: unused import\\n\"}\n",
			"{\"reason\":\"compiler-artifact\",\"executable\":null}\n",
			"{\"reason\":\"compiler-artifact\",\"executable\":\"/custom/runner.exe\"}\n",
			"{\"reason\":\"build-finished\",\"success\":true}\n"
		);
		assert_eq!(
			executable_in_messages(messages.as_bytes()).unwrap(),
			Some(PathBuf::from("/custom/runner.exe"))
		);
		let multiple = format!("{messages}{messages}");
		assert!(executable_in_messages(multiple.as_bytes()).is_err());
		assert_eq!(
			executable_in_messages(b"not Cargo JSON\n".as_slice()).unwrap(),
			None
		);
	}

	#[test]
	fn bundles_a_platform_guest_and_preserves_the_owned_runner() {
		for target in [Target::Linux, Target::Windows] {
			let root = std::env::temp_dir().canonicalize().unwrap().join(format!(
				"leptoskit-desktop-bundle-{}-{}",
				std::process::id(),
				target.platform()
			));
			let host = root.join(target.platform().to_string());
			write(&host.join("Cargo.toml"), "# owned manifest").unwrap();
			write(&host.join("src/main.rs"), "// owned window").unwrap();
			let generated = generated_dir(&root, target);
			write(&generated.join("assets/app.wasm"), "platform guest").unwrap();
			write(&root.join("runner"), "executable").unwrap();

			let mut config = LeptoskitConfig::default();
			config.app.name = "desktop_test".into();
			let bundle = assemble(&root, &config, target, &root.join("runner")).unwrap();
			let name = if matches!(target, Target::Windows) {
				format!("{}.exe", config.app.name)
			} else {
				config.app.name.clone()
			};

			assert_eq!(std::fs::read(bundle.join(name)).unwrap(), b"executable");
			assert_eq!(
				std::fs::read(bundle.join("assets/app.wasm")).unwrap(),
				b"platform guest"
			);
			assert_eq!(
				std::fs::read(host.join("src/main.rs")).unwrap(),
				b"// owned window"
			);
			std::fs::remove_dir_all(root).unwrap();
		}
	}
}
