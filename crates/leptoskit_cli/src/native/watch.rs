/// Generates the watchOS `SwiftUI` host, plugin registrant, `Info.plist`,
/// entitlements, and `Package.swift` / Xcode build configuration under
/// `.leptoskit/watchos/`.
pub(super) fn generate_watchos(
	root: &Path,
	config: &LeptoskitConfig,
	registry: &Registry,
) -> Result<()> {
	let dir = root.join(".leptoskit/watchos");
	std::fs::create_dir_all(&dir)?;

	let package_id = if config.native.package_id.is_empty() {
		leptoskit_config::default_package_id(&config.app.name)
	} else {
		config.native.package_id.clone()
	};
	let watch_cfg = &config.native.watchos;

	let mut imports = String::from("import Foundation\nimport LeptosKitBridge\n");
	let mut registrations = String::new();
	for (_, _plugin, implementation) in registry.implementations(Target::Watchos)? {
		if let Some(Implementation::Apple { module, ty }) = implementation.native() {
			writeln!(imports, "#if canImport({module})\nimport {module}\n#endif")?;
			writeln!(
				registrations,
				"        #if canImport({module})\n        dispatcher.register({ty}())\n        \
				 #endif"
			)?;
		}
	}

	let registrant_swift = format!(
		"// Generated by leptoskit for watchOS.\n{imports}\npublic enum GeneratedWatchPlugins \
		 {{\n    @MainActor\n    public static func register(dispatcher: NativeDispatcher) \
		 {{\n{registrations}    }}\n}}\n"
	);
	project::write(&dir.join("GeneratedPlugins.swift"), &registrant_swift)?;

	let mut bg_modes = Vec::new();
	if watch_cfg.workout_background {
		bg_modes.push("workout-processing");
	}
	for plugin in &registry.plugins {
		for mode in &plugin.apple_background_modes {
			if !bg_modes.contains(&mode.as_str()) {
				bg_modes.push(mode.as_str());
			}
		}
	}
	let mut bg_xml = String::new();
	for mode in &bg_modes {
		writeln!(bg_xml, "        <string>{mode}</string>")?;
	}
	let companion_xml = watch_cfg
		.companion_bundle_id
		.as_deref()
		.map_or_else(String::new, |id| {
			format!("    <key>WKCompanionAppBundleIdentifier</key>\n    <string>{id}</string>\n")
		});
	let standalone_tag = if watch_cfg.standalone {
		"<true/>"
	} else {
		"<false/>"
	};

	let info_plist = format!(
		"<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
		 <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \
		 \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
		 <plist version=\"1.0\">\n\
		 <dict>\n\
		     <key>CFBundleIdentifier</key>\n\
		     <string>{package_id}.watchkitapp</string>\n\
		     <key>CFBundleName</key>\n\
		     <string>{}</string>\n\
		     <key>CFBundleShortVersionString</key>\n\
		     <string>{}</string>\n\
		     <key>WKApplication</key>\n\
		     <true/>\n\
		     <key>WKRunsIndependentlyOfCompanionApp</key>\n\
		     {standalone_tag}\n\
		 {companion_xml}\
		     <key>WKBackgroundModes</key>\n\
		     <array>\n\
		 {bg_xml}\
		     </array>\n\
		 </dict>\n\
		 </plist>\n",
		config.app.name, config.app.version
	);
	project::write(&dir.join("Info.plist"), &info_plist)?;

	let mut entitlements_entries = String::new();
	let mut seen = std::collections::BTreeSet::new();
	for plugin in &registry.plugins {
		for ent in &plugin.apple_entitlements {
			if seen.insert(ent.as_str()) {
				writeln!(entitlements_entries, "    <key>{ent}</key>\n    <true/>")?;
			}
		}
	}
	let entitlements = format!(
		"<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
		 <!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \
		 \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
		 <plist version=\"1.0\">\n\
		 <dict>\n\
		 {entitlements_entries}\
		 </dict>\n\
		 </plist>\n"
	);
	project::write(&dir.join("WatchApp.entitlements"), &entitlements)?;

	let xcconfig = format!(
		"// Generated by leptoskit for watchOS.\nSDKROOT = watchos\nSUPPORTED_PLATFORMS = watchos \
		 watchsimulator\nWATCHOS_DEPLOYMENT_TARGET = {}\nPRODUCT_BUNDLE_IDENTIFIER = \
		 {package_id}.watchkitapp\nCODE_SIGN_ENTITLEMENTS = WatchApp.entitlements\n",
		watch_cfg.deployment_target
	);
	project::write(&dir.join("WatchHost.xcconfig"), &xcconfig)?;

	Ok(())
}

/// Builds the prepared watchOS host with `xcodebuild`.
pub(super) fn build_watchos(root: &Path, release: bool) -> Result<()> {
	let host = super::host_dir(root, Target::Watchos);
	let project_path = host.join("WatchHost.xcodeproj");
	let generated_dir = root.join(".leptoskit/watchos");
	anyhow::ensure!(
		cfg!(target_os = "macos"),
		"building watchOS apps requires macOS with Xcode installed; run `leptoskit native prepare \
		 watchos` on Linux to inspect the generated host files in {}",
		generated_dir.display()
	);
	let configuration = if release { "Release" } else { "Debug" };
	let mut command = Command::new("xcodebuild");
	if project_path.is_dir() {
		command.args(["-project", &project_path.to_string_lossy()]);
	} else {
		command.current_dir(&generated_dir);
	}
	command.args([
		"-sdk",
		"watchos",
		"-configuration",
		configuration,
		"-xcconfig",
		&generated_dir.join("WatchHost.xcconfig").to_string_lossy(),
		"CODE_SIGNING_ALLOWED=NO",
		"build",
	]);
	super::run_tool(&mut command)
}

fn write(path: &Path, content: impl AsRef<[u8]>) -> Result<()> {
	let parent = path
		.parent()
		.with_context(|| format!("could not create parent for {}", path.display()))?;
	std::fs::create_dir_all(parent)
		.with_context(|| format!("could not create {}", parent.display()))?;
	std::fs::write(path, content).with_context(|| format!("could not write {}", path.display()))
}

#[cfg(test)]
mod tests {
	use leptoskit_config::AppConfig;
	use leptoskit_config::NativeConfig;

	use super::*;

	#[test]
	fn scaffolds_wearos_host_files() {
		let root = std::env::temp_dir().join(format!("leptoskit-wearos-{}", std::process::id()));
		let _ = std::fs::remove_dir_all(&root);
		std::fs::create_dir_all(&root).unwrap();
		let config = LeptoskitConfig {
			app: AppConfig {
				name: "steps".into(),
				..AppConfig::default()
			},
			native: NativeConfig {
				package_id: "dev.leptoskit.steps".into(),
				targets: vec![NativeTarget::Wearos],
				..NativeConfig::default()
			},
			..LeptoskitConfig::default()
		};
		scaffold(&root, &config, NativeTarget::Wearos).unwrap();
		assert!(root.join("hosts/wearos/android/TileService.kt").is_file());
		assert!(root.join("hosts/wearos/guest.rs").is_file());
		let _ = std::fs::remove_dir_all(&root);
	}

	#[test]
	fn scaffolds_watchos_host_files() {
		let root = std::env::temp_dir().join(format!("leptoskit-watchos-{}", std::process::id()));
		let _ = std::fs::remove_dir_all(&root);
		std::fs::create_dir_all(&root).unwrap();
		let config = LeptoskitConfig {
			app: AppConfig {
				name: "steps".into(),
				..AppConfig::default()
			},
			native: NativeConfig {
				package_id: "dev.leptoskit.steps".into(),
				targets: vec![NativeTarget::Watchos],
				..NativeConfig::default()
			},
			..LeptoskitConfig::default()
		};
		scaffold(&root, &config, NativeTarget::Watchos).unwrap();
		assert!(root.join("hosts/watchos/swift/WatchApp.swift").is_file());
		assert!(root.join("hosts/watchos/guest.rs").is_file());
		let _ = std::fs::remove_dir_all(&root);
	}

	#[test]
	fn generates_watchos_host_artifacts() {
		let root =
			std::env::temp_dir().join(format!("leptoskit-watchos-gen-{}", std::process::id()));
		let _ = std::fs::remove_dir_all(&root);
		std::fs::create_dir_all(&root).unwrap();
		let config = LeptoskitConfig {
			app: AppConfig {
				name: "quant".into(),
				..AppConfig::default()
			},
			native: NativeConfig {
				package_id: "dev.leptoskit.quant".into(),
				..NativeConfig::default()
			},
			..LeptoskitConfig::default()
		};
		let registry = Registry {
			package: "quant_watchos".into(),
			plugins: Vec::new(),
			support: Vec::new(),
			bridge: root.join("bridge"),
			target: root.join("target"),
			host_features: vec![],
			devtools_feature: None,
			missing: Vec::new(),
			scene3d: false,
		};
		generate_watchos(&root, &config, &registry).unwrap();
		let plist = std::fs::read_to_string(root.join(".leptoskit/watchos/Info.plist")).unwrap();
		assert!(plist.contains("dev.leptoskit.quant.watchkitapp"));
		assert!(plist.contains("workout-processing"));
		assert!(root.join(".leptoskit/watchos/WatchHost.xcconfig").is_file());
		assert!(
			root.join(".leptoskit/watchos/GeneratedPlugins.swift")
				.is_file()
		);
		let _ = std::fs::remove_dir_all(&root);
	}

	#[test]
	fn validate_requires_package_id() {
		let config = LeptoskitConfig::default();
		assert!(validate(&config).is_err());
	}

	#[test]
	fn scaffold_rejects_non_watch_targets() {
		let root = std::env::temp_dir().join(format!("leptoskit-watch-bad-{}", std::process::id()));
		let _ = std::fs::remove_dir_all(&root);
		std::fs::create_dir_all(&root).unwrap();
		let config = LeptoskitConfig {
			native: NativeConfig {
				package_id: "dev.leptoskit.steps".into(),
				..NativeConfig::default()
			},
			..LeptoskitConfig::default()
		};
		assert!(scaffold(&root, &config, NativeTarget::Android).is_err());
		let _ = std::fs::remove_dir_all(&root);
	}
}
